void main() {
  // int stores whole numbers.
  int age = 22;
  print(age);

  // double stores decimal numbers.
  double height = 1.75;
  print(height);

  // String stores text.
  String name = "Yassin";
  print(name);

  // bool stores true or false values.
  bool isStudent = true;
  print(isStudent);

  // var lets Dart determine the type automatically.
  var country = "Rwanda";
  print(country);

  // dynamic can hold values of different types.
  dynamic value = 10;
  print(value);

  value = "Hello";
  print(value);

  // final can only be assigned once.
  final university = "Mount Kigali University";
  print(university);

  // university = "Another University";
  // Error: A final variable can only be assigned once.

  // const is a compile-time constant.
  const pi = 3.14159;
  print(pi);

  // pi = 3.14;
  // Error: A const variable cannot be reassigned.
}
