void main() {
  int a = 17;
  int b = 5;

  // Arithmetic Operators
  print("Addition: ${a + b}");
  print("Subtraction: ${a - b}");
  print("Multiplication: ${a * b}");
  print("Division: ${a / b}");
  print("Integer Division: ${a ~/ b}");
  print("Remainder: ${a % b}");

  print(""); // Blank line

  // Relational Operator
  print("Is a greater than b? ${a > b}");

  // Logical Operators
  print("Is a even AND b odd? ${a % 2 == 0 && b % 2 != 0}");
  print("Either a or b divisible by 3? ${a % 3 == 0 || b % 3 == 0}");
}
